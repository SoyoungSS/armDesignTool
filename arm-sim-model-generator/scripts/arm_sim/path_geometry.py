"""Shared generated primitive definitions, permitted assembly fits and motion bounds."""
from itertools import product
import numpy as np


def signed_distance(shape, half, points):
    """Analytic signed distance to a box or capped circular cylinder."""
    if shape == 'box':
        offsets = np.abs(points) - half
    else:
        offsets = np.stack((np.linalg.norm(points[..., :2], axis=-1) - half[0],
                            np.abs(points[..., 2]) - half[2]), axis=-1)
    return (np.linalg.norm(np.maximum(offsets, 0), axis=-1)
            + np.minimum(np.max(offsets, axis=-1), 0))


class Primitive:
    def __init__(self, link, part):
        self.link = link
        self.name = part['name']
        self.id = link + '/' + self.name
        self.geom = link + '_' + self.name + '_collision'
        self.kind = part['collision_kind']
        self.size = np.asarray(part.get('collision_size', part['size']), dtype=float)
        self.visual_size = np.asarray(part['size'], dtype=float)
        self.half = (self.size / 2 if self.kind == 'box' else
                     np.array([self.size[0], self.size[0], self.size[1] / 2]))
        self.T = np.array(part['T'], dtype=float)
        self.role = part.get('assembly_role', self.name)
        self.bore = part.get('bore_clear_radius_m')
        self.mesh = part['mesh']
        grid = np.array(list(product([-.8, 0., .8], repeat=3))) * self.half
        self.samples = grid[signed_distance(self.kind, self.half, grid) < 0]

    def record(self):
        return dict(id=self.id, link=self.link, name=self.name, mjcf_geom=self.geom,
                    shape=self.kind, size_m=self.size.tolist(), local_transform=self.T.tolist(),
                    role=self.role, visual_mesh=self.mesh)


def mating_regions(n, parts):
    """Each exception is constrained to a named generated fit and its design region."""
    pairs = {}
    for j in n['model']['joints']:
        prefix = j['name']
        if j['type'] == 'revolute':
            a = j['parent'] + '/' + prefix + '_stator'
            b = j['child'] + '/' + prefix + '_output_shaft'
            if a in parts and b in parts and parts[a].bore and parts[b].role == 'rotor':
                # The visual bore and design radius are generated by apply_layout.
                pairs[(a,b)] = dict(joint=prefix, kind='shaft_in_bore', frame=a,
                                     bore_radius_m=parts[a].bore,
                                     axial_half_length_m=parts[a].half[2],
                                     basis='joint_layout generated annular stator and coaxial output shaft')
        if j['type'] == 'prismatic':
            a, b = j['parent'] + '/rail', j['child'] + '/slider'
            if a in parts and b in parts:
                pairs[(a,b)] = dict(joint=prefix, kind='guide_and_slider', frame=a,
                                     guide_half_extents_m=parts[a].half.tolist(),
                                     travel_m=j['limits'], basis='parent guide and joint-owned moving carriage')
    return pairs


def in_fit(region, a, b, Ta, Tb, tolerance):
    relative = Ta[:3,:3].T @ (Tb[:3,3] - Ta[:3,3])
    axial = abs(Ta[:3,2] @ Tb[:3,2])
    if 1 - axial > 1e-10:
        return False
    if region['kind'] == 'shaft_in_bore':
        return np.linalg.norm(relative[:2]) + b.half[0] <= region['bore_radius_m'] + tolerance
    cross_section = np.abs(Tb[:3,:2].T @ Ta[:3,:2]) @ a.half[:2]
    return (np.linalg.norm(relative[:2]) <= tolerance and
            abs(relative[2]) <= a.half[2] + tolerance and
            np.all(cross_section <= b.half[:2] + tolerance))


def motion_bounds(joints, parts):
    # Downstream arc-length bound includes link offsets, slider excursions and part extents.
    reach = 0.
    lever = {}
    for j in reversed(joints):
        local = [np.linalg.norm(p.T[:3,3]) + np.linalg.norm(p.half)
                 for p in parts if p.link == j['child']]
        reach = max([reach, *local])
        lever[j['name']] = reach
        if j['type'] == 'prismatic':
            reach += max(abs(x) for x in j['limits'])
        reach += np.linalg.norm(j['origin']['xyz_m'])
    return lever, min(float(min(p.half)) for p in parts)
