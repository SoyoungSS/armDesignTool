"""Finite, filter-independent review of the collision primitives actually exported."""
from itertools import product
import math
import numpy as np

from .geometry import read_stl
from .math3d import forward
from .model import InputError, number, vector


def signed_distance(shape, half, points):
    """Analytic signed distance to a box or capped circular cylinder."""
    if shape == 'box':
        offsets = np.abs(points) - half
    else:
        offsets = np.stack((np.linalg.norm(points[..., :2], axis=-1) - half[0],
                            np.abs(points[..., 2]) - half[2]), axis=-1)
    return (np.linalg.norm(np.maximum(offsets, 0), axis=-1)
            + np.minimum(np.max(offsets, axis=-1), 0))


class Primitive:
    def __init__(self, link, part):
        self.link = link
        self.name = part['name']
        self.id = link + '/' + self.name
        self.geom = link + '_' + self.name + '_collision'
        self.kind = part['collision_kind']
        self.size = np.asarray(part.get('collision_size', part['size']), dtype=float)
        self.visual_size = np.asarray(part['size'], dtype=float)
        self.half = (self.size / 2 if self.kind == 'box' else
                     np.array([self.size[0], self.size[0], self.size[1] / 2]))
        self.T = np.array(part['T'], dtype=float)
        self.role = part.get('assembly_role', self.name)
        self.bore = part.get('bore_clear_radius_m')
        self.mesh = part['mesh']
        grid = np.array(list(product([-.8, 0., .8], repeat=3))) * self.half
        self.samples = grid[signed_distance(self.kind, self.half, grid) < 0]

    def record(self):
        return dict(id=self.id, link=self.link, name=self.name, mjcf_geom=self.geom,
                    shape=self.kind, size_m=self.size.tolist(), local_transform=self.T.tolist(),
                    role=self.role, visual_mesh=self.mesh)


def mating_regions(n, parts):
    """Each exception is constrained to a named generated fit and its design region."""
    pairs = {}
    for j in n['model']['joints']:
        prefix = j['name']
        if j['type'] == 'revolute':
            a = j['parent'] + '/' + prefix + '_stator'
            b = j['child'] + '/' + prefix + '_output_shaft'
            if a in parts and b in parts and parts[a].bore and parts[b].role == 'rotor':
                # The visual bore and design radius are generated by apply_layout.
                pairs[(a,b)] = dict(joint=prefix, kind='shaft_in_bore', frame=a,
                                     bore_radius_m=parts[a].bore,
                                     axial_half_length_m=parts[a].half[2],
                                     basis='joint_layout generated annular stator and coaxial output shaft')
        if j['type'] == 'prismatic':
            a, b = j['parent'] + '/rail', j['child'] + '/slider'
            if a in parts and b in parts:
                pairs[(a,b)] = dict(joint=prefix, kind='guide_and_slider', frame=a,
                                     guide_half_extents_m=parts[a].half.tolist(),
                                     travel_m=j['limits'], basis='parent guide and joint-owned moving carriage')
    return pairs


def in_fit(region, a, b, Ta, Tb, tolerance):
    relative = Ta[:3,:3].T @ (Tb[:3,3] - Ta[:3,3])
    axial = abs(Ta[:3,2] @ Tb[:3,2])
    if 1 - axial > 1e-10:
        return False
    if region['kind'] == 'shaft_in_bore':
        return np.linalg.norm(relative[:2]) + b.half[0] <= region['bore_radius_m'] + tolerance
    cross_section = np.abs(Tb[:3,:2].T @ Ta[:3,:2]) @ a.half[:2]
    return (np.linalg.norm(relative[:2]) <= tolerance and
            abs(relative[2]) <= a.half[2] + tolerance and
            np.all(cross_section <= b.half[:2] + tolerance))


def review_poses(n, parts, existing_cases):
    joints = n['model']['joints']
    poses = list(existing_cases)
    for j in joints:
        if j['type'] != 'fixed':
            for end, value in zip(('lower','upper'), j['limits']):
                poses.append((j['name'] + '_' + end, {**n['poses']['initial'], j['name']: value}))
    # Downstream arc-length bound includes link offsets, slider excursions and part extents.
    reach = 0.
    lever = {}
    for j in reversed(joints):
        local = [np.linalg.norm(p.T[:3,3]) + np.linalg.norm(p.half)
                 for p in parts if p.link == j['child']]
        reach = max([reach, *local])
        lever[j['name']] = reach
        if j['type'] == 'prismatic':
            reach += max(abs(x) for x in j['limits'])
        reach += np.linalg.norm(j['origin']['xyz_m'])
    resolution = min(float(min(p.half)) for p in parts)
    anchors = list(existing_cases[:2 + len(n['poses']['acceptance'])])
    segments = []
    for (start, q0), (end, q1) in zip(anchors, anchors[1:]):
        if not (in_joint_ranges(joints, q0) and in_joint_ranges(joints, q1)):
            segments.append(dict(start=start, end=end, requested=0, subdivisions=0,
                                 reason='assembly reference outside operating range'))
            continue
        travel = sum(abs(q1[j['name']] - q0[j['name']]) *
                     (lever[j['name']] if j['type'] == 'revolute' else 1.)
                     for j in joints if j['type'] != 'fixed')
        requested = max(1, math.ceil(2 * travel / resolution))
        divisions = min(128, requested)
        segments.append(dict(start=start, end=end, requested=requested, subdivisions=divisions,
                             max_relative_motion_bound_m=2 * travel/divisions))
        for i in range(1, divisions):
            poses.append((f'{start}->{end}@{i}/{divisions}',
                          {k: q0[k] + (q1[k]-q0[k])*i/divisions for k in q0}))
    return poses, dict(pose_count=len(poses), anchor_poses=[s for s, _ in existing_cases],
                       joint_limit_checks=[j['name'] for j in joints if j['type'] != 'fixed'],
                       interpolation='linear in joint coordinates', segments=segments,
                       target_motion_m=resolution, clearance_proven=False)


def in_joint_ranges(joints, q):
    return all(j['limits'][0] <= q[j['name']] <= j['limits'][1]
               for j in joints if j['type'] != 'fixed')


def project_radius(p, R, directions):
    local = directions @ R
    if p.kind == 'box':
        return np.abs(local) @ p.half
    return p.half[0]*np.linalg.norm(local[:,:2], axis=1) + p.half[2]*np.abs(local[:,2])


def narrow_phase(a, b, A, B, tolerance):
    """SAT for boxes. For cylinders use analytic separating axes and interior witnesses."""
    Ra, Rb = A[:3,:3], B[:3,:3]
    delta = B[:3,3] - A[:3,3]
    # Cylinder radial projections reject common skew/parallel separated pairs.
    axes = np.vstack((Ra.T, Rb.T, np.cross(Ra.T[:,None,:], Rb.T).reshape(-1,3), delta,
                      delta - Ra[:,2]*(delta @ Ra[:,2]), delta - Rb[:,2]*(delta @ Rb[:,2])))
    lengths = np.linalg.norm(axes, axis=1)
    dirs = axes[lengths > 1e-12] / lengths[lengths > 1e-12,None]
    overlaps = project_radius(a,Ra,dirs) + project_radius(b,Rb,dirs) - np.abs(dirs @ delta)
    least = float(min(overlaps))
    if least <= tolerance:
        return 'separated_or_touching', 0., None
    if a.kind == b.kind == 'box':
        return 'box_sat_overlap', least, None
    best_depth, best_point = 0., None
    for source, target, S, T in ((a,b,A,B), (b,a,B,A)):
        world = source.samples @ S[:3,:3].T + S[:3,3]
        local = (world - T[:3,3]) @ T[:3,:3]
        depths = -np.maximum(signed_distance(target.kind, target.half, local),
                             signed_distance(source.kind, source.half, source.samples))
        i = int(np.argmax(depths))
        if depths[i] > max(tolerance, best_depth):
            best_depth, best_point = float(depths[i]), world[i].tolist()
    if best_point is not None:
        return 'common_interior_point', best_depth, best_point
    return 'unresolved_candidate', 0., None


def distance_to_mesh(point, tris):
    """Shortest distance from one declared surface point to link-local STL triangles."""
    a, b, c = tris.transpose(1,0,2)
    edges = (b-a, c-b, a-c)
    normal = np.cross(edges[0], c-a)
    normal /= np.linalg.norm(normal, axis=1)[:,None]
    heights = np.sum((point-a)*normal, axis=1)
    distances = []
    inside = np.ones(len(tris), dtype=bool)
    for start, edge in zip((a,b,c), edges):
        v = point-start
        t = np.clip(np.sum(v*edge, axis=1) / np.sum(edge*edge, axis=1), 0, 1)
        distances.append(np.linalg.norm(v-edge*t[:,None], axis=1))
        inside &= np.sum(np.cross(edge,v)*normal, axis=1) >= 0
    distances.append(np.where(inside, abs(heights), np.inf))
    return float(np.min(distances))


def check_surfaces(n, parts, meshes):
    specs = n.get('contact_surfaces', [])
    if not isinstance(specs, list):
        raise InputError('contact_surfaces must be a list')
    specs = list(specs)
    for p in parts.values():
        if p.name != 'flange' or p.kind != 'cylinder':
            continue
        # The central disk of the generated planar flange is a known mating surface.
        radius, length = p.visual_size
        precision = 16 * np.finfo(np.float32).eps * (np.linalg.norm(p.T[:3,3]) + max(radius, length))
        for x,y in ((0,0), (.35,0), (-.35,0), (0,.35), (0,-.35)):
            point = p.T[:3,:3] @ [radius*x, radius*y, length/2] + p.T[:3,3]
            specs.append(dict(part=p.id,point_link_m=point.tolist(),tolerance_m=float(precision),
                              source='generated flange face; binary STL float32 roundoff'))
    results = []
    triangles = {}
    for spec in specs:
        if not isinstance(spec,dict) or set(spec) != {'part','point_link_m','tolerance_m','source'}:
            raise InputError('contact_surfaces requires part, point_link_m, tolerance_m and source')
        p = parts.get(spec['part']) if isinstance(spec['part'],str) else None
        if p is None or not isinstance(spec['source'], str) or not spec['source'].strip():
            raise InputError('unknown collision part or missing threshold source: '+str(spec))
        point = np.array(vector(spec['point_link_m'],'point_link_m'))
        limit = number(spec['tolerance_m'],'tolerance_m')
        if limit < 0:
            raise InputError('tolerance_m must be nonnegative')
        gap = float(signed_distance(p.kind,p.half,(point-p.T[:3,3]) @ p.T[:3,:3]))
        if p.mesh not in triangles:
            triangles[p.mesh] = read_stl(meshes/p.mesh)
        visual_gap = distance_to_mesh(point,triangles[p.mesh])
        status = 'passed'
        if visual_gap > limit:
            status = 'needs_review'
        elif abs(gap) > limit:
            status = 'failed'
        results.append(dict(**spec, proxy_signed_distance_m=gap, visual_distance_m=visual_gap,
                            pose='link-local (rigid surface)', status=status))
    return results


def review(n, meshes, existing_cases):
    parts = [Primitive(link,p) for link,g in n['geometry'].items()
             for p in g['parts'] if p['collision']]
    by_id = {p.id:p for p in parts}
    regions = mating_regions(n, by_id)
    poses, coverage = review_poses(n, parts, existing_cases)
    findings = {}
    named_poses = {}
    named_count = 2 + len(n['poses']['acceptance'])
    local = np.array([p.T for p in parts])
    halves = np.array([p.half for p in parts])
    owners = np.array([p.link for p in parts])
    left,right = np.where(np.triu(owners[:,None] != owners[None,:],1))
    tolerance = max(1e-12, np.finfo(float).eps * 128 * max(1., halves.max(),
                    np.linalg.norm(n['installation']['base_in_world']['xyz_m'])))
    for index, (label, q) in enumerate(poses):
        frames = forward(n,q)
        operational = in_joint_ranges(n['model']['joints'], q)
        pose_result = None
        if index < named_count:
            key = label if label not in named_poses else f'{label} [{index}]'
            pose_result = dict(name=label,q=q,in_joint_ranges=operational,status='passed',findings=[])
            named_poses[key] = pose_result
        world = np.stack([frames[p.link] for p in parts]) @ local
        centers = world[:,:3,3]
        extents = (np.abs(world[:,:3,:3]) @ halves[:,:,None])[:,:,0]
        active = np.all(extents[left]+extents[right]-abs(centers[left]-centers[right]) > tolerance,axis=1)
        for i,k in zip(left[active],right[active]):
            a,b,A,B = parts[i],parts[k],world[i],world[k]
            ids = (a.id,b.id)
            region = regions.get(ids)
            if region and in_fit(region,a,b,A,B,tolerance):
                continue
            method, depth, witness = narrow_phase(a,b,A,B,tolerance)
            if method == 'separated_or_touching':
                continue
            status = 'failed' if operational and method != 'unresolved_candidate' else 'needs_review'
            if pose_result is not None:
                if pose_result['status'] != 'failed':
                    pose_result['status'] = status
                pose_result['findings'].append(dict(parts=list(ids), method=method, status=status,
                                                    overlap_evidence_m=depth, witness_world_m=witness))
            entry = findings.get(ids)
            if entry is None or (status=='failed',depth) > (entry['status']=='failed',entry['overlap_evidence_m']):
                findings[ids] = dict(parts=list(ids), status=status, pose=label, q=q, method=method, in_joint_ranges=operational,
                                     overlap_evidence_m=depth, witness_world_m=witness,
                                     next_check='Inspect both collision primitives at the reported pose.')
    surfaces = check_surfaces(n, by_id, meshes)
    failures = [f for f in findings.values() if f['status']=='failed']
    limited = any(s['requested'] > s['subdivisions'] for s in coverage['segments'])
    status = 'passed'
    if findings or limited or any(s['status']=='needs_review' for s in surfaces):
        status = 'needs_review'
    if failures or any(s['status']=='failed' for s in surfaces):
        status = 'failed'
    return dict(schema_version='1.0',status=status,independent_of_engine_filters=True,
                parts=[p.record() for p in parts], coverage=coverage, named_pose_results=named_poses,
                mating_pairs=[dict(parts=list(ids), **region) for ids,region in regions.items()],
                findings=list(findings.values()), worst_case=max(failures,key=lambda f:f['overlap_evidence_m'],default=None),
                contact_surfaces=surfaces, contact_surface_status=('evaluated' if surfaces else 'not_declared'))
